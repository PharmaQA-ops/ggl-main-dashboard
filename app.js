/* =========================================
   OPEN PANEL
========================================= */

function openPanel(category) {

  const data = GGL_LINKS[category];

  if (!data) return;


  const title =
    document.getElementById("modalTitle");

  const subtitle =
    document.getElementById("modalSubtitle");

  const content =
    document.getElementById("modalContent");

  const modal =
    document.getElementById("modal");


  if (!title || !subtitle || !content || !modal) {
    console.error("Modal elements not found.");
    return;
  }


  title.innerText = data.title;

  subtitle.innerText = data.subtitle;


  let html =
    '<div class="resource-grid">';


  data.links.forEach(function(link, index) {

    html += `

      <a
        class="resource"
        href="${safeUrl(link.url)}"
        target="_blank"
        rel="noopener noreferrer"
        style="animation-delay:${index * 50}ms"
      >

        <i class="fa-solid ${escapeHtml(link.icon)}"></i>

        <span>
          ${escapeHtml(link.name)}
        </span>

      </a>

    `;

  });


  html += "</div>";


  content.innerHTML = html;


  modal.classList.add("show");

  document.body.classList.add("modal-open");

}


/* =========================================
   DIRECT LINK
========================================= */

function openLink(category) {

  const data =
    GGL_LINKS[category];

  if (!data || !data.links.length) {
    return;
  }


  const url =
    data.links[0].url;


  /*
     If URL is not configured,
     open the category panel.
  */

  if (!url || url === "#") {

    openPanel(category);

    return;

  }


  window.open(
    url,
    "_blank",
    "noopener,noreferrer"
  );

}


/* =========================================
   CLOSE MODAL
========================================= */

function closeModal() {

  const modal =
    document.getElementById("modal");


  if (!modal) return;


  modal.classList.remove("show");

  document.body.classList.remove("modal-open");

}


/* =========================================
   CLOSE MODAL OUTSIDE
========================================= */

function closeModalOutside(event) {

  if (
    event.target &&
    event.target.id === "modal"
  ) {

    closeModal();

  }

}


/* =========================================
   FAST LIVE SEARCH
   RUNS ON EVERY LETTER
========================================= */

function searchPortal() {

  const inputElement =
    document.getElementById("searchInput");

  const results =
    document.getElementById("searchResults");


  if (!inputElement || !results) {
    return;
  }


  const input =
    inputElement.value
      .toLowerCase()
      .trim();


  /*
     Clear results when search is empty.
  */

  if (!input) {

    results.innerHTML = "";

    results.classList.remove(
      "search-active"
    );

    return;

  }


  results.classList.add(
    "search-active"
  );


  let matches = [];


  /*
     SEARCH ALL CATEGORIES
  */

  Object.keys(GGL_LINKS)
    .forEach(function(category) {

      const data =
        GGL_LINKS[category];


      data.links.forEach(function(link) {

        const searchable = (

          category + " " +

          data.title + " " +

          data.subtitle + " " +

          link.name

        ).toLowerCase();


        /*
           Every-letter live matching
        */

        if (
          searchable.includes(input)
        ) {

          matches.push({

            category:
              category,

            name:
              link.name,

            icon:
              link.icon,

            url:
              link.url,

            searchable:
              searchable

          });

        }

      });

    });


  /*
     NO RESULTS
  */

  if (!matches.length) {

    results.innerHTML = `

      <div class="search-result-empty">

        <i class="fa-solid fa-magnifying-glass"></i>

        <span>
          No matching resource found
        </span>

      </div>

    `;

    return;

  }


  /*
     BUILD RESULTS
  */

  let html = "";


  matches.forEach(
    function(match, index) {

      html += `

        <a
          class="resource search-result"
          href="${safeUrl(match.url)}"
          target="_blank"
          rel="noopener noreferrer"
          style="animation-delay:${index * 35}ms"
        >

          <i class="fa-solid ${escapeHtml(match.icon)}"></i>

          <div>

            <strong>
              ${highlightText(
                match.name,
                input
              )}
            </strong>

            <br>

            <small>
              ${escapeHtml(match.category)}
            </small>

          </div>

        </a>

      `;

    }
  );


  results.innerHTML = `

    <div class="resource-grid">

      ${html}

    </div>

  `;

}


/* =========================================
   HIGHLIGHT SEARCH TEXT
========================================= */

function highlightText(
  text,
  search
) {

  const safeText =
    escapeHtml(text);


  if (!search) {
    return safeText;
  }


  const safeSearch =
    escapeRegExp(search);


  const regex =
    new RegExp(
      "(" + safeSearch + ")",
      "gi"
    );


  return safeText.replace(
    regex,
    "<mark>$1</mark>"
  );

}


/* =========================================
   ESCAPE REGEX
========================================= */

function escapeRegExp(value) {

  return String(value)
    .replace(
      /[.*+?^${}()|[\]\\]/g,
      "\\$&"
    );

}


/* =========================================
   ESCAPE HTML
========================================= */

function escapeHtml(value) {

  return String(value ?? "")
    .replace(
      /&/g,
      "&amp;"
    )
    .replace(
      /</g,
      "&lt;"
    )
    .replace(
      />/g,
      "&gt;"
    )
    .replace(
      /"/g,
      "&quot;"
    )
    .replace(
      /'/g,
      "&#039;"
    );

}


/* =========================================
   SAFE URL
========================================= */

function safeUrl(url) {

  if (!url) {
    return "#";
  }


  const value =
    String(url).trim();


  /*
     Allow normal web URLs,
     Google URLs and internal HTTP/HTTPS URLs.
  */

  if (
    value === "#" ||
    value.startsWith("https://") ||
    value.startsWith("http://")
  ) {

    return escapeHtml(value);

  }


  return "#";

}


/* =========================================
   DATE
========================================= */

function setDate() {

  const dateElement =
    document.getElementById(
      "currentDate"
    );


  if (!dateElement) return;


  const date =
    new Date();


  dateElement.innerText =
    date.toLocaleDateString(
      "en-IN",
      {
        day: "2-digit",
        month: "short",
        year: "numeric"
      }
    );

}


/* =========================================
   DARK MODE
========================================= */

function toggleTheme() {

  document.body
    .classList
    .toggle("dark");


  /*
     Remember user's preference
  */

  const isDark =
    document.body.classList.contains(
      "dark"
    );


  localStorage.setItem(
    "ggl-theme",
    isDark ? "dark" : "light"
  );

}


/* =========================================
   LOAD SAVED THEME
========================================= */

function loadTheme() {

  const savedTheme =
    localStorage.getItem(
      "ggl-theme"
    );


  if (savedTheme === "dark") {

    document.body
      .classList
      .add("dark");

  }

}


/* =========================================
   KEYBOARD SHORTCUTS
========================================= */

document.addEventListener(
  "keydown",
  function(event) {

    const activeElement =
      document.activeElement;


    /*
       "/" = Search
    */

    if (

      event.key === "/" &&

      activeElement &&
      activeElement.tagName !== "INPUT" &&

      activeElement.tagName !== "TEXTAREA"

    ) {

      event.preventDefault();


      const search =
        document.getElementById(
          "searchInput"
        );


      if (search) {

        search.focus();

      }

    }


    /*
       CTRL + K = Search
    */

    if (

      (event.ctrlKey || event.metaKey) &&

      event.key.toLowerCase() === "k"

    ) {

      event.preventDefault();


      const search =
        document.getElementById(
          "searchInput"
        );


      if (search) {

        search.focus();

        search.select();

      }

    }


    /*
       ESC = Close modal
    */

    if (
      event.key === "Escape"
    ) {

      closeModal();

    }

  }
);


/* =========================================
   SEARCH INPUT SETUP
   IMPORTANT:
   Search fires on EVERY LETTER
========================================= */

function setupSearch() {

  const searchInput =
    document.getElementById(
      "searchInput"
    );


  if (!searchInput) {

    console.warn(
      "searchInput not found"
    );

    return;

  }


  /*
     Remove inline dependency.

     This means search works even if
     oninput="searchPortal()" is missing.
  */

  searchInput.addEventListener(
    "input",
    searchPortal
  );


  /*
     Prevent form submission
  */

  searchInput.addEventListener(
    "keydown",
    function(event) {

      if (
        event.key === "Enter"
      ) {

        event.preventDefault();

      }

    }
  );

}


/* =========================================
   MODAL SETUP
========================================= */

function setupModal() {

  const modal =
    document.getElementById(
      "modal"
    );


  if (!modal) return;


  modal.addEventListener(
    "click",
    closeModalOutside
  );

}


/* =========================================
   WELCOME / LOADING SCREEN
   FAIL-SAFE
========================================= */

function hideWelcomeScreen() {

  const welcomeScreen =
    document.getElementById("welcomeScreen");

  if (!welcomeScreen) return;

  // Always hide after 2.5 seconds
  setTimeout(function () {

    welcomeScreen.classList.add("hide");

    // Completely remove it after animation
    setTimeout(function () {

      if (welcomeScreen) {
        welcomeScreen.remove();
      }

    }, 900);

  }, 2500);
}


/*
   FAIL-SAFE:
   Even if another JavaScript function has an error,
   the loading screen will disappear.
*/

window.addEventListener("load", function () {

  setTimeout(function () {

    const screen =
      document.getElementById("welcomeScreen");

    if (screen) {

      screen.classList.add("hide");

      setTimeout(function () {

        screen.remove();

      }, 900);

    }

  }, 3000);

});


